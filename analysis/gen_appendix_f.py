"""Appendix F: unified results table — AUROC and AURC for every signal x benchmark x backbone.
Plain-number cells (venue convention); missing design cells rendered as --.
Auto-fills verbalized/ptrue MedMCQA cells once elicitation jsonls exist.
Writes ../paper/tables/tab_full_results.tex (complete tabular); override with --out.
Usage: .venv/bin/python analysis/gen_appendix_f.py [--out PATH]
"""
import argparse
import csv
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from sklearn.metrics import roc_auc_score  # noqa: E402

R = Path("results")
DS = ("MedQA", "MMLU-Pro med", "MedMCQA")
H = ("MedQA", "MMLU-Pro", "MedMCQA")

SIGNALS = [  # (row label, auroc csv key, aurc csv key, flip orientation)
    ("Terminal agreement", "bl_terminal_agreement", "terminal", False),
    ("First-round agreement \\citep{wang2023selfconsistency}", "bl_r1_agreement(strict-ref)", "r1", False),
    ("Sequence log-probability", "bl_seq_logprob_mean", "seq_logprob", False),
    ("Answer entropy \\citep{kuhn2023semantic}", "f1_1_entropy_first", "ans_entropy", True),
    ("Verbalized confidence \\citep{tian2023justask}", "VERB", "verbalized", False),
    ("P(True) \\citep{kadavath2022know}", "PTRUE", "ptrue", False),
    ("\\method{} (process score)", "COMBINED_logreg", "combined", False),
]
BLOCKS = [
    ("Qwen3-8B", {"MedQA": "medqa", "MMLU-Pro med": "mmlupro", "MedMCQA": "medmcqa"}),
    ("HuatuoGPT-o1-8B", {"MedQA": "medqa_huatuo", "MMLU-Pro med": "mmlupro_huatuo", "MedMCQA": None}),
    ("Llama-3.1-8B", {"MedQA": "medqa_llama", "MMLU-Pro med": "mmlupro_llama", "MedMCQA": None}),
]
CONF_FILES = {"VERB": ("verbalized_{}.jsonl", "verbalized_conf"), "PTRUE": ("ptrue_{}.jsonl", "ptrue")}


def conf_auroc(stem: str, sig: str) -> str:
    tmpl, key = CONF_FILES[sig]
    p = R / tmpl.format(stem.split("_")[0])
    if not p.exists() or "_" in stem:  # self-report elicited on primary substrate only
        return "--"
    rows = [json.loads(l) for l in open(p)]
    ok = [r for r in rows if r.get(key) is not None and "error" not in r]
    if len(ok) < 100:
        return "--"
    y = np.array([int(r["correct"]) for r in ok])
    s = np.array([r[key] for r in ok], float)
    return f"{roc_auc_score(y, s):.3f}"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default="../paper/tables/tab_full_results.tex")
    args = parser.parse_args()
    auroc, aurc = {}, {}
    for _, dsmap in BLOCKS:
        for stem in dsmap.values():
            if stem is None or stem in auroc:
                continue
            auroc[stem] = {r[0]: float(r[1]) for r in csv.reader(open(R / f"auroc_table_{stem}.csv"))
                           if r and r[0] != "feature"}
            p = R / f"aurc_table_{stem}.csv"
            aurc[stem] = ({r[0]: float(r[1]) for r in csv.reader(open(p)) if r and r[0] != "signal"}
                          if p.exists() else {})

    def cell(stem, sig_auroc, sig_aurc, flip, metric):
        if stem is None:
            return "--"
        if metric == "auroc":
            if sig_auroc in CONF_FILES:
                return conf_auroc(stem, sig_auroc)
            v = auroc[stem].get(sig_auroc)
            if v is None:
                return "--"
            return f"{1 - v:.3f}" if flip else f"{v:.3f}"
        v = aurc[stem].get(sig_aurc)
        return "--" if v is None else f"{v:.3f}"

    out = ["% AUTO-GENERATED by analysis/gen_appendix_f.py — DO NOT EDIT",
           "\\begin{tabular}{lcccccc}", "\\toprule",
           "& \\multicolumn{3}{c}{AUROC $\\uparrow$} & \\multicolumn{3}{c}{AURC $\\downarrow$} \\\\",
           "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}",
           "Signal & " + " & ".join(H) + " & " + " & ".join(H) + " \\\\"]
    for bb, dsmap in BLOCKS:
        out.append("\\midrule")
        out.append(f"\\multicolumn{{7}}{{l}}{{\\emph{{{bb}}}}} \\\\")
        for label, ka, kc, flip in SIGNALS:
            cells = [cell(dsmap[d], ka, kc, flip, "auroc") for d in DS] + \
                    [cell(dsmap[d], ka, kc, flip, "aurc") for d in DS]
            if all(c == "--" for c in cells):
                continue
            if ka == "COMBINED_logreg":
                out.append("\\cmidrule(lr){1-7}")
            out.append(label + " & " + " & ".join(cells) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(out) + "\n")
    print(f"wrote {out_path} ({len(out)} lines)")


if __name__ == "__main__":
    main()
