"""Appendix G: ablation matrix — drop-one feature family + classifier swap, per benchmark.
KnowGuard-style 'w/o component' rows, plain AUROC cells, Full row on top.
Writes ../paper/tables/tab_ablation.tex (complete tabular).
Usage: .venv/bin/python analysis/gen_appendix_g.py
"""
import csv
import sys
from pathlib import Path

import numpy as np
from sklearn.metrics import roc_auc_score

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from abstain_layer.t3_evaluate import cv_scores, load  # noqa: E402

R = Path("results")
DATASETS = (("MedQA", "features_medqa.csv", "auroc_table_medqa.csv"),
            ("MMLU-Pro", "features_mmlupro.csv", "auroc_table_mmlupro.csv"),
            ("MedMCQA", "features_medmcqa.csv", "auroc_table_medmcqa.csv"))
FAMILIES = (("agreement dynamics", "f0_"), ("answer-distribution dynamics", "f1_"),
            ("minority dynamics", "f2_"), ("rationale signals", "f3_"),
            ("retrieval dynamics", "f4_"))


def main() -> None:
    rows = {"Full process score": [], "GBT in place of logistic regression": []}
    for name, _ in FAMILIES:
        rows[f"w/o {name}"] = []
    for ds, feat, auroc_csv in DATASETS:
        X, y, cols, _ = load(R / feat)
        proc = [i for i, c in enumerate(cols) if not c.startswith("bl_")]
        full = roc_auc_score(y, cv_scores(X, y, proc, "logreg"))
        rows["Full process score"].append(full)
        for name, pref in FAMILIES:
            keep = [i for i in proc if not cols[i].startswith(pref)]
            rows[f"w/o {name}"].append(roc_auc_score(y, cv_scores(X, y, keep, "logreg")))
        gbt = {r[0]: float(r[1]) for r in csv.reader(open(R / auroc_csv))
               if r and r[0] != "feature"}["COMBINED_gbt"]
        rows["GBT in place of logistic regression"].append(gbt)
        print(f"{ds}: full={full:.3f}")

    out = ["% AUTO-GENERATED by analysis/gen_appendix_g.py — DO NOT EDIT",
           "\\begin{tabular}{lccc}", "\\toprule",
           "Configuration & MedQA & MMLU-Pro & MedMCQA \\\\", "\\midrule"]
    order = ["Full process score"] + [f"w/o {n}" for n, _ in FAMILIES]
    full_cells = " & ".join(f"\\textbf{{{v:.3f}}}" for v in rows["Full process score"])
    out.append(f"\\textbf{{Full process score}} & {full_cells} \\\\")
    for label in order[1:]:
        cells = " & ".join(f"{v:.3f}" for v in rows[label])
        out.append(f"\\quad {label} & {cells} \\\\")
    out.append("\\midrule")
    label = "GBT in place of logistic regression"
    out.append(f"{label} & " + " & ".join(f"{v:.3f}" for v in rows[label]) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    Path("../paper/tables/tab_ablation.tex").write_text("\n".join(out) + "\n")
    for label in order + [label]:
        print(f"{label:42s} " + "  ".join(f"{v:.3f}" for v in rows[label]))


if __name__ == "__main__":
    main()
