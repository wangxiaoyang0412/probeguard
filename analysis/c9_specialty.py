"""C9: per-specialty certification on the MedQA unanimous layer (S-MedQA labels).
Repeated-split protocol identical to holes.h3 (alpha=0.15, delta=0.025, R=50).
Outputs results/c9_specialty.csv + ../paper/tables/tab_specialty.tex (tabular body; override with --out).
Usage: .venv/bin/python analysis/c9_specialty.py [--out PATH]
"""
import argparse
import csv
import json
import sys
from pathlib import Path

import numpy as np
from sklearn.model_selection import train_test_split

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from abstain_layer.phase1_conformal import evaluate, ltt_threshold  # noqa: E402

ALPHA, DELTA, R, MIN_N = 0.15, 0.025, 50, 25


def load() -> tuple:
    probe = {json.loads(l)["qid"]: json.loads(l) for l in open("results/probe_pilot_medqa.jsonl")
             if "error" not in json.loads(l)}
    soft = {r["qid"]: float(r["f3_5_mean_bidir"]) for r in csv.DictReader(open("results/soft_f3_medqa_ua.csv"))}
    spec = json.load(open("results/medqa_specialty_labels.json"))
    qids, y, s = [], [], []
    for q, r in probe.items():
        sq = f"medqa_{q}"
        if sq in soft:
            qids.append(str(q))
            y.append(int(r["consensus_correct"]))
            s.append((r["keep_rate"], soft[sq]))
    y, s = np.array(y), np.array(s)
    z = lambda a: (a - a.mean()) / (a.std() + 1e-12)
    comb = z(s[:, 0]) + z(s[:, 1])
    labels = np.array([spec.get(q, "Unlabeled") for q in qids])
    return comb, y, labels


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default="../paper/tables/tab_specialty.tex")
    args = parser.parse_args()
    comb, y, labels = load()
    idx = np.arange(len(y))
    counts = {g: int((labels == g).sum()) for g in set(labels)}
    groups = sorted([g for g, n in counts.items() if n >= MIN_N and g != "Unlabeled"],
                    key=lambda g: -counts[g])
    print(f"S1 layer n={len(y)}, labeled={int((labels != 'Unlabeled').sum())}, groups(min {MIN_N}): {len(groups)}")

    cov = {g: [] for g in groups}
    risk = {g: [] for g in groups}
    for seed in range(R):
        cal, te = train_test_split(idx, test_size=0.5, random_state=seed, stratify=y)
        thr, _ = ltt_threshold(comb[cal], y[cal], ALPHA, delta=DELTA)
        for g in groups:
            m = te[labels[te] == g]
            if len(m) == 0:
                continue
            c, rk = evaluate(comb[m], y[m], thr)
            cov[g].append(c)
            risk[g].append(rk if c > 0 else np.nan)

    rows = []
    for g in groups:
        n_g = counts[g]
        err_g = float(1 - y[labels == g].mean())
        cv = np.array(cov[g])
        rk = np.array(risk[g])
        rows.append((g, n_g, 100 * err_g, cv.mean(), 100 * np.nanmean(rk)))
    rows.sort(key=lambda r: -r[3])

    with open("results/c9_specialty.csv", "w") as fp:
        w = csv.writer(fp)
        w.writerow(["specialty", "n_s1", "ua_err_pct", "cert_coverage", "risk_pct"])
        for r in rows:
            w.writerow([r[0], r[1], f"{r[2]:.1f}", f"{r[3]:.3f}", f"{r[4]:.1f}"])

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as fp:
        fp.write("% AUTO-GENERATED by analysis/c9_specialty.py — DO NOT EDIT\n")
        fp.write("\\begin{tabular}{lcccc}\n\\toprule\n")
        fp.write("Specialty & $n$ & Unanimous-layer error (\\%) & Certified coverage & Realized risk (\\%) \\\\\n\\midrule\n")
        for g, n_g, err, c, rk in rows:
            rk_s = "--" if np.isnan(rk) else f"{rk:.1f}"
            fp.write(f"{g} & {n_g} & {err:.1f} & {c:.2f} & {rk_s} \\\\\n")
        fp.write("\\bottomrule\n\\end{tabular}\n")
    for r in rows:
        print(f"{r[0]:28s} n={r[1]:3d} uaerr={r[2]:4.1f}% cov={r[3]:.2f} risk={r[4]:.1f}%")


if __name__ == "__main__":
    main()
